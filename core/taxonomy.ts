import type { ServiceTemplate } from './service-catalog'

/**
 * Server-owned map of legal industries for idea scouting. Models never choose a topic or a
 * search phrase: the scheduler assigns a topic, and `searchQuery` only accepts phrases listed
 * here. Excluded areas of the master prompt (gambling, adult content, politics, medical, legal
 * and investment advice, student work, fake engagement, bulk mailing, personal data, bypassing
 * blocks) are deliberately absent.
 */
export type TaxonomyCategory = {
  id: string
  label: string
  /** Short locative phrase for feed lines: "ищет в общепите". */
  where: string
}
export type TaxonomyAngle = {
  title: string
  problem: string
  /** A farm template that can deliver this idea, or null when a person is needed. */
  template: ServiceTemplate | null
}
export type TaxonomyTopic = {
  id: string
  category: string
  label: string
  audience: string
  /** Demand, competitors and prices. The server sends them to search as they are. */
  queries: [string, string, ...string[]]
  /** What counts as a demand signal for this topic. */
  hints: string[]
  /** Seeds for explicit demo answers and for the scout's memory of possible directions. */
  angles: TaxonomyAngle[]
}

