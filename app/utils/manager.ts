export function managerReason(code: string) {
  if (
    ['DAILY_LOSS_LIMIT', 'DRAWDOWN_LIMIT', 'OWNER_PAUSE', 'OWNER_STOP', 'OWNER_EXIT'].includes(
      code,
    ) ||
    code.startsWith('TRADING_')
  )
    return tradingReason(code)
  return (
    reasons[code] ||
    (code ? 'Проверка пока не завершена. Состояние уточнится при следующем разборе.' : '')
  )
}

